-- Clothing furni and the avatar figure sets they hand over, taken from the shipped assets.
--
-- Regenerate with tools/catalog_converter/scan_purchasable_clothing.py, which reads
-- furnidata_json.json and figuredata.xml. Do not hand-edit: the mapping is the hotel's
-- own data, and there are thousands of rows.
--
-- The furni are selected by furnidata's `specialtype` = 23, which is what the client's
-- numeric furni category actually comes from. The `category` string beside it disagrees --
-- only 588 items say 'clothing' where 2 802 carry specialtype 23, the rest saying 'unknow'
-- (Habbo's own typo), 'unknown' or 'other'. Reading the string would have seeded a fifth of
-- the set and silently dropped the rest.
--
-- Matched by classname, which is NOT unique in furniture_definitions: a classname shared by
-- several definitions grants its sets through every one of them, which is the correct
-- reading -- each is the same furni to the client.
--
-- 2794 clothing furni, 3687 furni/set pairs, 3280 distinct sets.
-- 8 carried specialtype 23 with no usable customparams and are left out: they would
-- redeem into silence.
-- 162 classnames appear more than once in the furnidata itself.

