-- Pet food and water, rebuilt 2026-08-03.
--
-- Columns: furniture_definition_id, pet_type, nutrition, energy, thirst, max_uses
--
-- Habbo counts four needs: hunger, thirst, energy and happiness. Food fills the belly and gives
-- a little energy back -- "after a pet has eaten, their energy will go up and you will be able to
-- start training again" -- while water slakes thirst and nothing else. Thirst used to be read off
-- energy, so a drink also cancelled the pet's need for a nap.
--
-- The previous seed assigned each food to exactly one pet type, handed out sequentially in file
-- order, on a legend that did not match the client: it read 8=devil, 10=horse, 16=meow where the
-- client's pet.type.* keys say 8=Spider, 10=Chicken, 15=Horse, 16=Monsterplant. The result fed
-- Salmon to spiders, Hay to the Monster, Dragon food to cats, and gave the Monsterplant -- which
-- the room code excludes from eating outright -- a bowl of Webbed Grapes. Only types 0-18 were
-- covered at all, so every bunny, pigeon, baby, dinosaur and cow starved by construction.
--
-- Authority for each assignment, in order:
--   1. the furni's own description in furnidata_json.json, where it names a species outright
--      ("Sweets for your lion", "for spiders only", "Your chicks will love it",
--      "for your large farmyard pets", "the barking one");
--   2. failing that, the species' diet -- meat and bones to the carnivores, greens to the
--      herbivores, fish to the cats.
-- Pet type ids are the client's pet.type.* keys, never Arcturus' ordering.
--
-- Monsterplants (type 16) are deliberately absent: they are rooted, and RoomPetSystem skips them
-- before feeding is ever considered. They are watered, not fed.
--
-- max_uses mirrors the definition's total_states, so a bowl empties in as many servings as it has
-- frames to show. The three one-state bowl families are the exception: they cannot show a fill
-- level at all, so they carry the classic six servings and the logic leaves their state alone.
--
-- Re-running is harmless: the delete scopes to the rows this file owns.

